#include "Delay.h"
#include "app_config.h"
#include "ti_msp_dl_config.h"

/* =========================================================
 * 按 CPU 周期粗略延时
 * ========================================================= */
void Delay_cycles(volatile uint32_t n)
{
    while (n--) {
        __NOP();
    }
}

/* =========================================================
 * 粗略微秒延时
 * 按主频近似换算，仅适合短阻塞等待
 * ========================================================= */
void Delay_us(uint32_t us)
{
    while (us--) {
        /* 约 1us：80MHz 下按经验循环常数校准 */
        Delay_cycles(CPU_CLOCK_HZ / 1000000U / 5U);
    }
}

/* =========================================================
 * 粗略毫秒延时
 * 注意：阻塞整个主循环，只适合路口预延时等短等待
 * ========================================================= */
void Delay_ms(uint32_t ms)
{
    while (ms--) {
        Delay_cycles(CPU_CLOCK_HZ / 12000U);
    }
}
