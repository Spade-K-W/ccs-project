/* ========================================================
 * OLED 控制引脚
 * 你的 SysConfig：
 * RES -> GPIO_OLED_OLED_RES_PIN
 * DC  -> GPIO_OLED_OLED_DC_PIN
 * CS  -> SPI_0 的硬件 CS0
 * ======================================================== */
static inline void oled_set_dc_data(void)
{
    DL_GPIO_setPins(GPIO_OLED_PORT, GPIO_OLED_OLED_DC_PIN);
}

static inline void oled_set_dc_cmd(void)
{
    DL_GPIO_clearPins(GPIO_OLED_PORT, GPIO_OLED_OLED_DC_PIN);
}

static inline void oled_set_res_high(void)
{
    DL_GPIO_setPins(GPIO_OLED_PORT, GPIO_OLED_OLED_RES_PIN);
}

static inline void oled_set_res_low(void)
{
    DL_GPIO_clearPins(GPIO_OLED_PORT, GPIO_OLED_OLED_RES_PIN);
}

/* ========================================================
 * SPI 写一个字节（带超时，避免 SPI 异常时卡死主循环）
 * ======================================================== */
static void oled_spi_write(uint8_t data)
{
    uint32_t guard = 50000U;

    while (DL_SPI_isBusy(SPI_0_INST)) {
        if (--guard == 0U) {
            return;
        }
    }

    DL_SPI_transmitData8(SPI_0_INST, data);

    guard = 50000U;
    while (DL_SPI_isBusy(SPI_0_INST)) {
        if (--guard == 0U) {
            return;
        }
    }
}

void oled_write_cmd(uint8_t cmd)
{
    oled_set_dc_cmd();
    oled_spi_write(cmd);
}

void oled_write_data(uint8_t data)
{
    oled_set_dc_data();
    oled_spi_write(data);
}

void oled_write_datas(const uint8_t *buf, uint32_t len)
{
    uint32_t i;

    if ((buf == 0) || (len == 0U)) {
        return;
    }

    oled_set_dc_data();

    for (i = 0; i < len; i++) {
        uint32_t guard = 50000U;

        while (DL_SPI_isBusy(SPI_0_INST)) {
            if (--guard == 0U) {
                return;
            }
        }

        DL_SPI_transmitData8(SPI_0_INST, buf[i]);
    }

    {
        uint32_t guard = 50000U;

        while (DL_SPI_isBusy(SPI_0_INST)) {
            if (--guard == 0U) {
                return;
            }
        }
    }
}

void oled_init(void)
{
    oled_set_dc_cmd();
    oled_set_res_high();

    delay_ms(20);

    oled_set_res_low();
    delay_ms(20);
    oled_set_res_high();
    delay_ms(20);

    oled_write_cmd(0xAE);
    oled_write_cmd(0xD5);
    oled_write_cmd(0x80);
    oled_write_cmd(0xA8);
    oled_write_cmd(0x3F);
    oled_write_cmd(0xD3);
    oled_write_cmd(0x00);
    oled_write_cmd(0x40);
    oled_write_cmd(0x8D);
    oled_write_cmd(0x14);
    oled_write_cmd(0xA1);
    oled_write_cmd(0xC8);
    oled_write_cmd(0xDA);
    oled_write_cmd(0x12);
    oled_write_cmd(OLED_SET_CONTRAST);
    oled_write_cmd(0xCF);
    oled_write_cmd(0xD9);
    oled_write_cmd(0xF1);
    oled_write_cmd(0xDB);
    oled_write_cmd(0x40);
    oled_write_cmd(0xA4);
    oled_write_cmd(0xA6);
    oled_write_cmd(OLED_DISPLAY_ON);

    oled_clear();
}

void oled_set_pos(uint8_t page, uint8_t column)
{
    if (page >= OLED_PAGES) {
        page = OLED_PAGES - 1;
    }

    if (column >= OLED_WIDTH) {
        column = OLED_WIDTH - 1;
    }

    column += 4 ;
    oled_write_cmd(OLED_SET_PAGE + page);
    oled_write_cmd(OLED_SET_COLUMN_LOW + (column & 0x0F));
    oled_write_cmd(OLED_SET_COLUMN_HI + ((column >> 4) & 0x0F));
}

void oled_clear(void)
{
    uint8_t page;
    uint8_t column;

    for (page = 0; page < OLED_PAGES; page++) {
        oled_set_pos(page, 0);
        for (column = 0; column < OLED_WIDTH; column++) {
            oled_write_data(0x00);
        }
    }
}

void oled_fill(uint8_t fill_data)
{
    uint8_t page;
    uint8_t column;

    for (page = 0; page < OLED_PAGES; page++) {
        oled_set_pos(page, 0);
        for (column = 0; column < OLED_WIDTH; column++) {
            oled_write_data(fill_data);
        }
    }
}

void oled_display_string(uint8_t page, uint8_t column, const char *str)
{
    uint32_t i = 0;
    uint8_t cur_column = column;
    unsigned char ch;

    if ((str == 0) || (page >= OLED_PAGES)) {
        return;
    }

    while (str[i] != '\0') {
        ch = (unsigned char)str[i];

        if ((cur_column + 6U) > OLED_WIDTH) {
            break;
        }

        oled_set_pos(page, cur_column);
        if(ch>=32 && ch<=127){
            oled_write_datas(oled_font_6x8[ch - 32], 6);
        }else {
            oled_write_datas(oled_font_6x8[0], 6);//非法字符为空格
        }


        cur_column += 6U;
        i++;
    }
}

void oled_display_num(uint8_t page, uint8_t column, uint8_t num)
{
    char buf[2];

    if (num > 9U) {
        return;
    }

    buf[0] = (char)('0' + num);
    buf[1] = '\0';

    oled_display_string(page, column, buf);
}

void oled_display_on(void)
{
    oled_write_cmd(OLED_DISPLAY_ON);
}

void oled_display_off(void)
{
    oled_write_cmd(OLED_DISPLAY_OFF);
}

/* ========================================================
 * 浮点数显示，避免 printf 浮点支持问题
 * ======================================================== */
static void oled_format_float_2(char *buf, uint32_t size, const char *name, float value)
{
    int32_t v;
    int32_t integer;
    int32_t decimal;

    v = (int32_t)(value * 100.0f);

    if (v < 0) {
        integer = (-v) / 100;
        decimal = (-v) % 100;
        snprintf(buf, size, "%s:-%d.%02d", name, integer, decimal);
    } else {
        integer = v / 100;
        decimal = v % 100;
        snprintf(buf, size, "%s: %d.%02d", name, integer, decimal);
    }
}

void oled_display_z_angle(uint8_t page, float angle)
{
    char buf[22];

    oled_format_float_2(buf, sizeof(buf), "ZAngle", angle);

    oled_display_string(page, 0, "                     ");
    oled_display_string(page, 0, buf);
}

void oled_display_z_gyro(uint8_t page, float gyro)
{
    char buf[22];

    oled_format_float_2(buf, sizeof(buf), "GyroZ ", gyro);

    oled_display_string(page, 0, "                     ");
    oled_display_string(page, 0, buf);
}