#ifndef OLED_H
#define OLED_H

#include <stdint.h>
#include <stdbool.h>

/* ========================================================
 * OLED显示屏参数
 * 分辨率: 128 x 64
 * ======================================================== */
#define OLED_WIDTH          128
#define OLED_HEIGHT         64
#define OLED_PAGES          8   /* 64 / 8 = 8页 */

/* 常用命令 */
#define OLED_SET_CONTRAST   0x81
#define OLED_DISPLAY_ON     0xAF
#define OLED_DISPLAY_OFF    0xAE
#define OLED_SET_PAGE       0xB0
#define OLED_SET_COLUMN_LOW 0x00
#define OLED_SET_COLUMN_HI  0x10

/* ========================================================
 * OLED初始化
 * 配置SPI和GPIO控制引脚（DC、RES）
 * ======================================================== */
void oled_init(void);

/* ========================================================
 * 向OLED写入命令字节
 * cmd: 命令字节
 * ======================================================== */
void oled_write_cmd(uint8_t cmd);

/* ========================================================
 * 向OLED写入数据字节
 * data: 数据字节
 * ======================================================== */
void oled_write_data(uint8_t data);

/* ========================================================
 * 向OLED批量写入数据
 * buf: 数据缓冲区指针
 * len: 数据字节数
 * ======================================================== */
void oled_write_datas(const uint8_t *buf, uint32_t len);

/* ========================================================
 * 设置OLED显示光标位置
 * page: 页号 (0-7)
 * column: 列号 (0-127)
 * ======================================================== */
void oled_set_pos(uint8_t page, uint8_t column);

/* ========================================================
 * 清空OLED显示屏
 * ======================================================== */
void oled_clear(void);

/* ========================================================
 * 填充OLED显示屏（全白或全黑）
 * fill_data: 填充数据 (0x00=黑, 0xFF=白)
 * ======================================================== */
void oled_fill(uint8_t fill_data);

/* ========================================================
 * 显示一行ASCII字符串
 * page: 页号 (0-7)
 * column: 列号 (0-127)
 * str: 字符串指针
 * ======================================================== */
void oled_display_string(uint8_t page, uint8_t column, const char *str);

/* ========================================================
 * 显示单个数字
 * page: 页号
 * column: 列号
 * num: 要显示的数字 (0-9)
 * ======================================================== */
void oled_display_num(uint8_t page, uint8_t column, uint8_t num);

/* ========================================================
 * 打开显示
 * ======================================================== */
void oled_display_on(void);

/* ========================================================
 * 关闭显示
 * ======================================================== */
void oled_display_off(void);
/* 新增：显示 Z 轴角度和角速度 */
void oled_display_z_angle(uint8_t page, float angle);
void oled_display_z_gyro(uint8_t page, float gyro);

#endif  // OLED_H